/** The rule a finding's code names → { section, rule }. */
export function ruleOf(code) {
  if (Object.hasOwn(EXACT, code)) return EXACT[code];
  for (const [p, r] of PREFIX) if (String(code).startsWith(p)) return r;
  return { section: '', rule: '' };
}

/** A finding with its rule and section, when it doesn't carry its own (schema findings do). */
export function withRule(problem) {
  if (problem.rule && problem.section) return problem;
  const r = ruleOf(problem.code);
  return { ...problem, rule: problem.rule || r.rule, section: problem.section || r.section };
}
