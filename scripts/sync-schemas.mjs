#!/usr/bin/env node
// Bring the specification's JSON Schemas and its checker's modules into the library (PRD REF-4, REF-2):
//   VRMXA_Specification/schemas/*.schema.json   → src/schema/schemas.js  (one module, so a browser bundle has them)
//   VRMXA_Specification/tools/check/lib/*.js     → src/spec/*.js          (the same files, byte for byte: validate.js runs in
//                                                                          browsers; check.js, zip.js and conformance.js in Node)
// The specification is the source; test/schema.test.mjs fails when the copies differ from it.
//   node scripts/sync-schemas.mjs [--spec <VRMXA_Specification folder>] [--check]
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findSpecDir } from '../src/node/spec.js';

const here = dirname(fileURLToPath(import.meta.url));
const argSpec = process.argv.indexOf('--spec');
const specAssets = findSpecDir();
const SPEC = argSpec > 0 ? process.argv[argSpec + 1] : specAssets ? join(specAssets, '..', '..') : null;
if (!SPEC) { console.error('the specification was not found beside this repository: pass --spec'); process.exit(2); }
const files = readdirSync(join(SPEC, 'schemas')).filter((f) => f.endsWith('.schema.json')).sort();
const schemas = Object.fromEntries(files.map((f) => [f, JSON.parse(readFileSync(join(SPEC, 'schemas', f), 'utf8'))]));
const moduleText = `// Generated by scripts/sync-schemas.mjs from VRMXA_Specification/schemas/: do not edit here.\n// ${files.length} schemas, JSON Schema 2020-12.\nexport default ${JSON.stringify(schemas, null, 1)};\n`;
const out = { 'src/schema/schemas.js': moduleText };
for (const f of readdirSync(join(SPEC, 'tools/check/lib')).filter((x) => x.endsWith('.js')).sort()) out[`src/spec/${f}`] = readFileSync(join(SPEC, 'tools/check/lib', f), 'utf8');
if (process.argv.includes('--check')) {
  const stale = Object.entries(out).filter(([p, t]) => { try { return readFileSync(join(here, '..', p), 'utf8') !== t; } catch { return true; } }).map(([p]) => p);
  if (stale.length) { console.error(`out of date with the specification: ${stale.join(', ')} (run node scripts/sync-schemas.mjs)`); process.exit(1); }
  console.log('the schemas and the checker modules match the specification');
} else {
  mkdirSync(join(here, '..', 'src/spec'), { recursive: true });
  for (const [p, t] of Object.entries(out)) writeFileSync(join(here, '..', p), t);
  console.log(`${files.length} schemas and ${Object.keys(out).length - 1} checker modules copied from ${SPEC}`);
}
